#!/usr/bin/env python3
"""Render TrueType fonts into Adafruit GFXfont headers for the firmware.

Used for src/features/commute/CommuteFonts.h. Needs Pillow (pip install pillow).

    python tools/ttf_to_gfxfont.py Inter.ttf src/features/commute/CommuteFonts.h

Each entry in FONTS below becomes one GFXfont: name, pixel size, weight (for a
variable font's wght axis) and the character range. Text fonts cover Latin-1
(0x20-0xFF), so the firmware converts UTF-8 to Latin-1 before printing.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

# name, px size, weight, first, last
FONTS = [
    ("commuteTime",  68, 600, 0x30, 0x3A),   # 0-9 and ':'
    ("commuteNum",   44, 600, 0x2D, 0x39),   # '-' '.' '/' 0-9
    ("commuteMin",   34, 600, 0x2D, 0x39),   # Home: minutes until the trip
    ("commuteBold18", 19, 650, 0x20, 0xFF),
    ("commuteBold16", 16, 650, 0x20, 0xFF),
    ("commuteReg16",  16, 450, 0x20, 0xFF),
    ("commuteBold13", 13, 650, 0x20, 0xFF),   # the hourly row: 30 px columns
    ("commuteReg12",  12, 500, 0x20, 0xFF),
]
THRESHOLD = 110   # 0-255: lower = bolder 1-bit glyphs


def load(path, size, weight):
    f = ImageFont.truetype(path, size)
    try:
        axes = f.get_variation_axes()
        vals = []
        for a in axes:
            name = a.get("name", b"")
            name = name.decode() if isinstance(name, bytes) else str(name)
            if "eight" in name:
                vals.append(weight)
            elif "ptical" in name:
                vals.append(min(a["maximum"], max(a["minimum"], size)))
            else:
                vals.append(a["default"])
        f.set_variation_by_axes(vals)
    except OSError:
        pass   # not a variable font
    return f


def render(path, name, size, weight, first, last):
    font = load(path, size, weight)
    ascent, descent = font.getmetrics()
    bitmap = bytearray()
    glyphs = []
    for code in range(first, last + 1):
        ch = bytes([code]).decode("latin-1")
        adv = int(round(font.getlength(ch))) if code >= 0x20 and not 0x7F <= code < 0xA0 else 0
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls") if adv else (0, 0, 0, 0)
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        offset = len(bitmap)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            bits, n, acc = [], 0, 0
            for y in range(h):
                for x in range(w):
                    acc = (acc << 1) | (1 if img.getpixel((x, y)) >= THRESHOLD else 0)
                    n += 1
                    if n == 8:
                        bits.append(acc)
                        n, acc = 0, 0
            if n:
                bits.append(acc << (8 - n))
            bitmap.extend(bits)
        else:
            w = h = 0
            x0 = y0 = 0
        glyphs.append((offset, w, h, adv, x0, y0))

    out = [f"// {name}: {size}px, weight {weight}, 0x{first:02X}-0x{last:02X}"]
    out.append(f"static const uint8_t {name}Bitmaps[] PROGMEM = {{")
    for i in range(0, len(bitmap), 16):
        out.append("  " + ", ".join(f"0x{b:02X}" for b in bitmap[i:i + 16]) + ",")
    out.append("};")
    out.append(f"static const GFXglyph {name}Glyphs[] PROGMEM = {{")
    for code, g in zip(range(first, last + 1), glyphs):
        out.append(f"  {{{g[0]}, {g[1]}, {g[2]}, {g[3]}, {g[4]}, {g[5]}}},  // 0x{code:02X}")
    out.append("};")
    # extern: the font objects are shared (CommuteDraw.h declares them).
    out.append(f"extern const GFXfont {name} PROGMEM = {{(uint8_t*){name}Bitmaps, "
               f"(GFXglyph*){name}Glyphs, 0x{first:02X}, 0x{last:02X}, {ascent + descent}}};")
    return "\n".join(out), len(bitmap)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, dst = sys.argv[1], sys.argv[2]
    parts = [
        "// GENERATED by tools/ttf_to_gfxfont.py -- do not edit by hand.",
        "// Glyphs rendered from Inter (https://rsms.me/inter/), SIL Open Font License 1.1.",
        "#pragma once",
        "#include <Arduino.h>",
        "#include <gfxfont.h>",
        "",
    ]
    total = 0
    for spec in FONTS:
        text, n = render(src, *spec)
        parts.append(text)
        parts.append("")
        total += n
    open(dst, "w").write("\n".join(parts))
    print(f"{dst}: {len(FONTS)} fonts, {total} bitmap bytes")


if __name__ == "__main__":
    main()
